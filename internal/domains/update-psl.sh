#!/usr/bin/env bash
# Updates the embedded Public Suffix List (make psl): the newest commit of
# github.com/publicsuffix/list on main that is at least 14 days old, with its
# SHA-256 written to psl_version.go (a test checks the file against it).
set -euo pipefail
cd "$(dirname "$0")"
since=$(date -u -d '14 days ago' +%Y-%m-%dT%H:%M:%SZ)
sha=$(gh api "repos/publicsuffix/list/commits?sha=main&until=$since&per_page=1" -q '.[0].sha')
date=$(gh api "repos/publicsuffix/list/commits/$sha" -q '.commit.committer.date')
curl -sSfL "https://raw.githubusercontent.com/publicsuffix/list/$sha/public_suffix_list.dat" -o public_suffix_list.dat.new
grep -q '===BEGIN ICANN DOMAINS===' public_suffix_list.dat.new
mv public_suffix_list.dat.new public_suffix_list.dat
sum=$(sha256sum public_suffix_list.dat | cut -d' ' -f1)
cat > psl_version.go <<EOF
// Code generated by update-psl.sh; DO NOT EDIT.

package domains

// The embedded Public Suffix List: github.com/publicsuffix/list at this commit.
const (
	PSLCommit = "$sha"
	PSLDate   = "$date"
	PSLSHA256 = "$sum"
)
EOF
echo "Public Suffix List: $sha ($date), sha256 $sum"
