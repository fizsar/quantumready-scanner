"""Summarize the testssl.sh JSON files in test/tlslab/reference into SUMMARY.md.

Usage: python3 -I test/tlslab/summarize.py test/tlslab/reference
"""

import json
import pathlib
import re
import sys

PROTOCOLS = [("SSLv2", "SSLv2"), ("SSLv3", "SSLv3"), ("TLS1", "TLS 1.0"), ("TLS1_1", "TLS 1.1"),
             ("TLS1_2", "TLS 1.2"), ("TLS1_3", "TLS 1.3")]
CIPHER_ID = re.compile(r"^cipher-(ssl2|ssl3|tls1|tls1_1|tls1_2|tls1_3)_x([0-9a-f]+)$")
PROTO_NAME = {"ssl2": "SSLv2", "ssl3": "SSLv3", "tls1": "TLS 1.0", "tls1_1": "TLS 1.1", "tls1_2": "TLS 1.2", "tls1_3": "TLS 1.3"}


def summarize(path):
    entries = json.loads(path.read_text())
    if isinstance(entries, dict):  # --jsonfile-pretty
        entries = [f for s in entries.get("scanResult", []) for v in s.values() if isinstance(v, list) for f in v]
    by_id = {}
    for e in entries:
        by_id.setdefault(e.get("id"), []).append(e.get("finding", ""))
    protocols = [name for key, name in PROTOCOLS
                 if any(f.startswith(("offered", "vulnerable")) for f in by_id.get(key, []))]  # SSLv2: "vulnerable with 4 ciphers"
    ciphers = {}
    dh_bits = set()
    for key, findings in by_id.items():
        m = CIPHER_ID.match(key or "")
        if not m:
            continue
        for f in findings:
            cols = f.split()
            # "TLSv1.2 x9e DHE-RSA-AES128-GCM-SHA256 DH 1024 AESGCM 128 TLS_DHE_RSA_WITH_AES_128_GCM_SHA256"
            name = cols[-1] if cols else ""
            ciphers.setdefault(PROTO_NAME[m.group(1)], {})[int(m.group(2), 16)] = name
            kx = re.search(r"\bDH (\d+)\b", f)
            if kx:
                dh_bits.add(int(kx.group(1)))
    first = lambda k: (by_id.get(k) or [""])[0]
    return {
        "protocols": protocols,
        "ciphers": ciphers,
        "dh_bits": sorted(dh_bits),
        "curves": first("FS_ECDHE_curves"),
        "kems": first("FS_KEMs"),
        "dh_groups": first("DH_groups"),
    }


def main(directory):
    d = pathlib.Path(directory)
    out = ["# testssl.sh reference (generated by summarize.py; do not edit)", ""]
    for path in sorted(d.glob("*.json")):
        s = summarize(path)
        out.append(f"## {path.stem}")
        out.append("")
        out.append(f"- Protocols: {', '.join(s['protocols']) or 'none'}")
        for proto, suites in s["ciphers"].items():
            names = ", ".join(f"{name} (0x{cid:04x})" for cid, name in sorted(suites.items()))
            out.append(f"- {proto} suites ({len(suites)}): {names}")
        if s["dh_bits"]:
            out.append(f"- DH sizes seen in suites: {', '.join(map(str, s['dh_bits']))} bits")
        for label, key in (("ECDHE curves", "curves"), ("KEMs", "kems"), ("DH groups", "dh_groups")):
            if s[key]:
                out.append(f"- {label}: {s[key]}")
        out.append("")
    (d / "SUMMARY.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "test/tlslab/reference")
